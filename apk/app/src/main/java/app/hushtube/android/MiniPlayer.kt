/**
 * In-app floating mini player that looks like picture-in-picture (current YouTube app):
 * a rounded 16:9 video window floating over the page. Native, so it survives WebView page
 * loads (Invidious is multi-page). Drag it anywhere; on release it snaps to the nearest
 * corner (a flick throws it there). Tap = controls overlay (expand · play/pause · close),
 * auto-hiding after 3 s. Thin red progress line along the bottom edge.
 * The same view fills the window in system PiP (when leaving the app).
 */
@OptIn(UnstableApi::class)
class MiniPlayer(
    private val act: MainActivity,
    private val parent: FrameLayout,
    private val onExpand: (Item, Long) -> Unit,
    private val onChanged: () -> Unit,
) {
    data class Item(val id: String, val title: String, val author: String)

    var item: Item? = null
        private set
    private var player: ExoPlayer? = null
    private var inPip = false

    val isActive get() = item != null

    // ---- background audio preference (default ON: "keep listening" is the point) ----
    private val prefs = act.getSharedPreferences("settings", android.content.Context.MODE_PRIVATE)
    var bgAudio: Boolean
        get() = prefs.getBoolean("bgAudio", true)
        set(v) { prefs.edit().putBoolean("bgAudio", v).apply() }

    private fun syncBgIcon() {
        bgBtn.setImageResource(if (bgAudio) R.drawable.ic_mini_bgaudio else R.drawable.ic_mini_bgaudio_off)
        bgBtn.colorFilter = android.graphics.PorterDuffColorFilter(
            if (bgAudio) Color.WHITE else Color.parseColor("#8AFFFFFF"), android.graphics.PorterDuff.Mode.SRC_IN)
        bgBtn.contentDescription = if (bgAudio) "Background audio on — tap to turn off"
                                   else "Background audio off — tap to turn on"
    }

    /**
     * Keep the media notification in sync (it is what survives minimize / screen off). The
     * notification itself is generated by PlaybackService's MediaSession from this player —
     * artwork, scrubber and transport controls all come from the player state and metadata.
     */
    fun notifyBg() {
        if (inPip) return                                  // PiP window: no notification needed
        val p = player
        if (item == null || p == null) { PlaybackService.stop(act); return }
        if (!bgAudio) { PlaybackService.stop(act); return }
        // Idle means released/stopped: nothing to advertise, and starting the service for it
        // would only produce a dead notification.
        if (p.playbackState == Player.STATE_IDLE) { PlaybackService.stop(act); return }
        PlaybackService.start(act, p)
    }
    val isPlaying get() = player?.let { it.isPlaying || (it.playWhenReady && it.playbackState == Player.STATE_BUFFERING) } == true
    fun positionMs(): Long = player?.currentPosition ?: 0L

    private val density = act.resources.displayMetrics.density
    private fun dp(v: Int) = (v * density).toInt()

    // area the window floats in (px): below the page's top bar, above its bottom tab bar
    private var areaTop = 0; private var areaBottom = 0; private var areaLeft = 0; private var areaRight = 0
    private var corner = BR

    // ---- views ----
    private val radius = 12 * density
    val container = FrameLayout(act).apply {
        setBackgroundColor(Color.BLACK)
        elevation = 14 * density
        outlineProvider = object : ViewOutlineProvider() {
            override fun getOutline(view: View, outline: Outline) {
                outline.setRoundRect(0, 0, view.width, view.height, if (inPip) 0f else radius)
            }
        }
        clipToOutline = true
        visibility = View.GONE
    }
    private val playerView = PlayerView(act).apply {
        useController = false
        resizeMode = AspectRatioFrameLayout.RESIZE_MODE_FIT
        setShutterBackgroundColor(Color.BLACK)
        setBackgroundColor(Color.BLACK)
        isClickable = false
        isFocusable = false
    }
    private val controls = FrameLayout(act).apply {
        setBackgroundColor(Color.parseColor("#73000000"))
        visibility = View.GONE
        alpha = 0f
    }
    private val playBtn = iconButton(R.drawable.ic_mini_pause, "Pause", 10) { toggle(); showControls() }
    private val expandBtn = iconButton(R.drawable.ic_mini_expand, "Expand", 8) { expand() }
    private val closeBtn = iconButton(R.drawable.ic_mini_close, "Close", 8) { close() }
    // "keep audio when the app is minimized" — lives here because this is the player that does it
    private val bgBtn = iconButton(R.drawable.ic_mini_bgaudio, "Play audio when app is minimized", 8) {
        val on = !bgAudio
        bgAudio = on
        syncBgIcon()
        onChanged()   // -> MainActivity.onMiniChanged -> updatePipParams: PiP auto-enter arms/disarms
        android.widget.Toast.makeText(act, if (on) "Audio keeps playing when you minimize"
                                           else "Audio stops when you minimize", android.widget.Toast.LENGTH_SHORT).show()
    }
    private val track = View(act).apply { setBackgroundColor(Color.parseColor("#4DFFFFFF")) }
    private val progress = View(act).apply { setBackgroundColor(Color.parseColor("#FF0033")); pivotX = 0f; scaleX = 0f }
    // Thumbnail shown over the black player until the first frame renders, plus a spinner
    // while buffering — the mini must never look dead (v1.14).
    private val poster = ImageView(act).apply {
        scaleType = ImageView.ScaleType.CENTER_CROP
        visibility = View.GONE
    }
    private val spinner = android.widget.ProgressBar(act).apply {
        isIndeterminate = true
        indeterminateTintList = android.content.res.ColorStateList.valueOf(Color.WHITE)
        visibility = View.GONE
    }
    private var posterTag: String? = null

    private val handler = Handler(Looper.getMainLooper())
    private val tick = object : Runnable {
        override fun run() {
            val p = player ?: return
            val d = p.duration
            progress.scaleX = if (d > 0) (p.currentPosition.toFloat() / d).coerceIn(0f, 1f) else 0f
            handler.postDelayed(this, 500)
        }
    }
    private val autoHide = Runnable { hideControls() }

    init {
        container.addView(playerView, FrameLayout.LayoutParams(ViewGroup.LayoutParams.MATCH_PARENT, ViewGroup.LayoutParams.MATCH_PARENT))
        container.addView(poster, FrameLayout.LayoutParams(ViewGroup.LayoutParams.MATCH_PARENT, ViewGroup.LayoutParams.MATCH_PARENT))
        container.addView(spinner, FrameLayout.LayoutParams(dp(36), dp(36), Gravity.CENTER))
        controls.addView(playBtn, FrameLayout.LayoutParams(dp(52), dp(52), Gravity.CENTER))
        controls.addView(expandBtn, FrameLayout.LayoutParams(dp(40), dp(40), Gravity.TOP or Gravity.START))
        controls.addView(closeBtn, FrameLayout.LayoutParams(dp(40), dp(40), Gravity.TOP or Gravity.END))
        controls.addView(bgBtn, FrameLayout.LayoutParams(dp(40), dp(40), Gravity.BOTTOM or Gravity.START))
        container.addView(controls, FrameLayout.LayoutParams(ViewGroup.LayoutParams.MATCH_PARENT, ViewGroup.LayoutParams.MATCH_PARENT))
        container.addView(track, FrameLayout.LayoutParams(ViewGroup.LayoutParams.MATCH_PARENT, dp(3), Gravity.BOTTOM))
        container.addView(progress, FrameLayout.LayoutParams(ViewGroup.LayoutParams.MATCH_PARENT, dp(3), Gravity.BOTTOM))
        parent.addView(container, FrameLayout.LayoutParams(dp(200), dp(112), Gravity.TOP or Gravity.START))
        // re-place on rotation / fold changes
        parent.addOnLayoutChangeListener { _, l, t, r, b, ol, ot, or_, ob ->
            if ((r - l != or_ - ol || b - t != ob - ot) && isActive && !inPip) container.post { place(false) }
        }
        installGestures()
    }

    private fun iconButton(res: Int, desc: String, padDp: Int, onClick: () -> Unit) = ImageButton(act).apply {
        setImageResource(res)
        contentDescription = desc
        background = null
        scaleType = ImageView.ScaleType.FIT_CENTER
        setPadding(dp(padDp), dp(padDp), dp(padDp), dp(padDp))
        setColorFilter(Color.WHITE)
        setOnClickListener { onClick() }
    }

    /** The floating window covers content (like YouTube); the page reserves no space. */
    fun cssHeight(): Int = 0

    /** Float area in px (top = status bar + page top bar, bottom = nav inset + page tab bar). */
    fun setInsets(topPx: Int, bottomPx: Int, leftPx: Int, rightPx: Int) {
        areaTop = topPx; areaBottom = bottomPx; areaLeft = leftPx; areaRight = rightPx
        if (!inPip && isActive) container.post { place(false) }
    }

    // ---- floating geometry ----
    private fun winW(): Int {
        val w = parent.width.takeIf { it > 0 } ?: act.resources.displayMetrics.widthPixels
        return (w * 0.52f).toInt().coerceIn(dp(176), dp(360))
    }

    private fun cornerXY(c: Int, w: Int, h: Int): Pair<Float, Float> {
        val m = dp(12)
        val x = if (c == TL || c == BL) areaLeft + m else parent.width - areaRight - m - w
        val y = if (c == TL || c == TR) areaTop + m else parent.height - areaBottom - m - h
        return Pair(x.toFloat(), y.toFloat())
    }

    private fun place(animate: Boolean) {
        val w = winW(); val h = w * 9 / 16
        val lp = container.layoutParams as FrameLayout.LayoutParams
        if (lp.width != w || lp.height != h || lp.gravity != (Gravity.TOP or Gravity.START)) {
            container.layoutParams = FrameLayout.LayoutParams(w, h, Gravity.TOP or Gravity.START)
        }
        val (x, y) = cornerXY(corner, w, h)
        if (animate) {
            container.animate().translationX(x).translationY(y).setDuration(240)
                .setInterpolator(DecelerateInterpolator(1.6f)).start()
        } else {
            container.translationX = x; container.translationY = y
        }
        container.invalidateOutline()
    }

    // ---- playback ----
    // Shadow player (v1.13): while the page video plays, a muted ExoPlayer plays the same
    // stream in the background, so swiping down ADOPTS an already-buffered player -> no
    // cold-start freeze. Owned by MainActivity's report() traffic.
    private var shadow: ExoPlayer? = null
    private var shadowId: String? = null

    fun warm(it: Item, src: String, positionMs: Long, playing: Boolean, thumbUrl: String? = null) {
        if (item != null) return                       // mini player already owns playback
        val s = shadow
        if (s != null && shadowId == it.id) {
            s.playWhenReady = playing
            // Only correct LARGE drift (page seek / long watch): every seek discards the
            // shadow's forward buffer, and that buffer is exactly what makes adopt instant.
            if (playing && Math.abs(s.currentPosition - positionMs) > 30000) s.seekTo(positionMs)
            return
        }
        s?.release()
        shadow = null; shadowId = null
        if (!playing) return
        val p = ExoPlayer.Builder(act).build()
        p.setAudioAttributes(
            AudioAttributes.Builder().setUsage(C.USAGE_MEDIA).setContentType(C.AUDIO_CONTENT_TYPE_MOVIE).build(),
            /* handleAudioFocus = */ false)           // must never steal focus from the page video
        p.volume = 0f
        p.setMediaItem(
            MediaItem.Builder().setUri(src).setMediaId(it.id)
                .setMediaMetadata(MediaMetadata.Builder().setTitle(it.title).setArtist(it.author)
                    .setArtworkUri(thumbUrl?.let { u -> android.net.Uri.parse(u) }).build())
                .build(),
            positionMs)
        p.playWhenReady = true
        p.prepare()
        shadow = p; shadowId = it.id
    }

    fun pauseShadow() { shadow?.playWhenReady = false }
    fun dropShadow() { shadow?.release(); shadow = null; shadowId = null }

    /** Zero-gap handover: if the shadow already has this video, adopt it as the mini player. */
    fun adoptShadow(it: Item, positionMs: Long, play: Boolean, visibleBar: Boolean, thumbUrl: String?): Boolean {
        val p = shadow ?: return false
        if (shadowId != it.id) return false
        shadow = null; shadowId = null
        release()
        item = it
        p.setAudioAttributes(
            AudioAttributes.Builder().setUsage(C.USAGE_MEDIA).setContentType(C.AUDIO_CONTENT_TYPE_MOVIE).build(),
            /* handleAudioFocus = */ true)
        p.setHandleAudioBecomingNoisy(true)
        p.volume = 1f
        wire(p)
        if (Math.abs(p.currentPosition - positionMs) > 750) p.seekTo(positionMs)  // in-buffer -> instant
        p.playWhenReady = play
        // Poster covers a still-buffering shadow for a moment; onRenderedFirstFrame clears it
        // (re-fires on the new surface even if frames rendered before).
        attach(p, it, thumbUrl, visibleBar)
        return true
    }

    private fun wire(p: ExoPlayer) {
        p.addListener(object : Player.Listener {
            override fun onIsPlayingChanged(isPlaying: Boolean) { syncBusy(); syncPlayIcon(); onChanged(); notifyBg() }
            override fun onPlayWhenReadyChanged(playWhenReady: Boolean, reason: Int) { syncBusy(); syncPlayIcon(); onChanged(); notifyBg() }
            override fun onPlaybackStateChanged(state: Int) {
                if (state == Player.STATE_ENDED) { p.playWhenReady = false; p.seekTo(0); showControls() }
                syncBusy(); syncPlayIcon(); onChanged(); notifyBg()
            }
            override fun onRenderedFirstFrame() { hidePoster() }
        })
    }

    /** Spinner while we want to play but are still buffering. */
    private fun syncBusy() {
        val p = player
        val busy = p != null && p.playWhenReady && p.playbackState == Player.STATE_BUFFERING && !p.isPlaying
        spinner.visibility = if (busy) View.VISIBLE else View.GONE
    }

    private fun showPoster(url: String, id: String) {
        posterTag = id
        poster.scaleType = ImageView.ScaleType.FIT_CENTER   // mqdefault is 16:9 — fits the window exactly
        poster.visibility = View.VISIBLE
        poster.setImageDrawable(null)
        Thread {
            try {
                val conn = java.net.URL(url).openConnection() as java.net.HttpURLConnection
                conn.connectTimeout = 5000; conn.readTimeout = 5000
                val bmp = android.graphics.BitmapFactory.decodeStream(conn.inputStream)
                conn.disconnect()
                if (bmp != null) handler.post { if (posterTag == id) poster.setImageBitmap(bmp) }
            } catch (_: Exception) { }
        }.start()
    }
    private fun hidePoster() {
        posterTag = null
        if (poster.visibility != View.VISIBLE) return
        poster.animate().alpha(0f).setDuration(160).withEndAction {
            poster.visibility = View.GONE; poster.alpha = 1f
        }.start()
    }

    private fun attach(p: ExoPlayer, it: Item, thumbUrl: String?, visibleBar: Boolean) {
        player = p
        playerView.player = p
        if (thumbUrl != null) showPoster(thumbUrl, it.id) else hidePoster()
        syncBusy()
        syncPlayIcon()
        handler.removeCallbacks(tick); handler.post(tick)
        syncBgIcon()
        hideControls(immediate = true)
        if (visibleBar) {
            container.animate().cancel()
            container.alpha = 0f
            container.visibility = View.VISIBLE
            container.post {
                place(false)
                // shrink in from a bigger size, like the player collapsing into the corner
                container.pivotX = container.width.toFloat(); container.pivotY = container.height.toFloat()
                container.scaleX = 1.25f; container.scaleY = 1.25f
                container.animate().scaleX(1f).scaleY(1f).alpha(1f).setDuration(220)
                    .setInterpolator(DecelerateInterpolator()).start()
            }
        }
        onChanged()
    }

    fun show(it: Item, src: String, thumbUrl: String?, positionMs: Long, play: Boolean, visibleBar: Boolean = true) {
        release()
        dropShadow()
        item = it
        val p = ExoPlayer.Builder(act).build()
        p.setAudioAttributes(
            AudioAttributes.Builder().setUsage(C.USAGE_MEDIA).setContentType(C.AUDIO_CONTENT_TYPE_MOVIE).build(),
            /* handleAudioFocus = */ true
        )
        p.setHandleAudioBecomingNoisy(true)
        p.setMediaItem(
            MediaItem.Builder().setUri(src).setMediaId(it.id)
                .setMediaMetadata(MediaMetadata.Builder().setTitle(it.title).setArtist(it.author)
                    .setArtworkUri(thumbUrl?.let { u -> android.net.Uri.parse(u) }).build())
                .build(),
            positionMs
        )
        wire(p)
        p.playWhenReady = play
        p.prepare()
        attach(p, it, thumbUrl, visibleBar)
    }

    fun pause() { player?.playWhenReady = false }

    fun resumePlayback() { player?.playWhenReady = true }

    /** Handed off while the app was backgrounded (no bar shown): reveal it when the user is back. */
    fun revealIfHidden() {
        if (!isActive || inPip || container.visibility == View.VISIBLE) return
        container.alpha = 1f; container.scaleX = 1f; container.scaleY = 1f
        container.visibility = View.VISIBLE
        container.post { place(false) }
    }

    /** Expand pressed: window disappears the same frame; the player keeps running until
     *  MainActivity closes us when the page video takes over (v1.26 gap-free expand). */
    fun hideNow() {
        container.animate().cancel()
        hideControls(immediate = true)
        container.visibility = View.GONE
    }

    private fun toggle() {
        val p = player ?: return
        if (p.playbackState == Player.STATE_ENDED) p.seekTo(0)
        p.playWhenReady = !p.playWhenReady
    }

    private fun syncPlayIcon() {
        val playing = player?.playWhenReady == true
        playBtn.setImageResource(if (playing) R.drawable.ic_mini_pause else R.drawable.ic_mini_play)
        playBtn.contentDescription = if (playing) "Pause" else "Play"
    }

    private fun showControls() {
        handler.removeCallbacks(autoHide)
        controls.animate().cancel()
        controls.visibility = View.VISIBLE
        controls.animate().alpha(1f).setDuration(120).start()
        handler.postDelayed(autoHide, 3000)
    }

    private fun hideControls(immediate: Boolean = false) {
        handler.removeCallbacks(autoHide)
        controls.animate().cancel()
        if (immediate) { controls.alpha = 0f; controls.visibility = View.GONE; return }
        controls.animate().alpha(0f).setDuration(150).withEndAction { controls.visibility = View.GONE }.start()
    }

    fun expand() {
        val it = item ?: return
        onExpand(it, positionMs())     // MainActivity loads the watch page; its onPageStarted closes us
    }

    fun close() {
        PlaybackService.stop(act)
        dropShadow()
        if (!isActive) return
        release()
        item = null
        container.animate().cancel()
        container.pivotX = container.width / 2f; container.pivotY = container.height / 2f
        container.animate().alpha(0f).scaleX(0.8f).scaleY(0.8f).setDuration(150).withEndAction {
            container.visibility = View.GONE
            container.alpha = 1f; container.scaleX = 1f; container.scaleY = 1f
        }.start()
        onChanged()
    }

    private fun release() {
        handler.removeCallbacks(tick)
        handler.removeCallbacks(autoHide)
        playerView.player = null
        player?.release(); player = null
        progress.scaleX = 0f
    }

    // ---- system picture-in-picture: the same player fills the window ----
    fun setPipLayout(pip: Boolean) {
        inPip = pip
        if (pip) {
            hideControls(immediate = true)
            track.visibility = View.GONE; progress.visibility = View.GONE
            container.animate().cancel()
            container.visibility = View.VISIBLE
            container.translationX = 0f; container.translationY = 0f
            container.scaleX = 1f; container.scaleY = 1f; container.alpha = 1f
            container.layoutParams = FrameLayout.LayoutParams(ViewGroup.LayoutParams.MATCH_PARENT, ViewGroup.LayoutParams.MATCH_PARENT)
            container.invalidateOutline()
        } else {
            track.visibility = View.VISIBLE; progress.visibility = View.VISIBLE
            container.visibility = if (isActive) View.VISIBLE else View.GONE
            if (isActive) container.post { place(false) }
        }
    }

    // ---- gestures: drag anywhere, snap to nearest corner; tap = controls ----
    @SuppressLint("ClickableViewAccessibility")
    private fun installGestures() {
        var downX = 0f; var downY = 0f; var startX = 0f; var startY = 0f
        var dragging = false
        var vt: VelocityTracker? = null
        val slop = dp(8)
        val listener = View.OnTouchListener { _, e ->
            if (inPip) return@OnTouchListener false
            val v = container
            when (e.actionMasked) {
                MotionEvent.ACTION_DOWN -> {
                    downX = e.rawX; downY = e.rawY
                    startX = v.translationX; startY = v.translationY
                    dragging = false
                    v.animate().cancel()
                    vt?.recycle(); vt = VelocityTracker.obtain().also { it.addMovement(e) }
                    true
                }
                MotionEvent.ACTION_MOVE -> {
                    vt?.addMovement(e)
                    val dx = e.rawX - downX; val dy = e.rawY - downY
                    if (!dragging && hypot(dx, dy) > slop) { dragging = true; hideControls() }
                    if (dragging) {
                        v.translationX = (startX + dx).coerceIn(0f, (parent.width - v.width).toFloat())
                        v.translationY = (startY + dy).coerceIn(0f, (parent.height - v.height).toFloat())
                    }
                    true
                }
                MotionEvent.ACTION_UP, MotionEvent.ACTION_CANCEL -> {
                    vt?.addMovement(e)
                    vt?.computeCurrentVelocity(1000)
                    val vx = vt?.xVelocity ?: 0f; val vy = vt?.yVelocity ?: 0f
                    vt?.recycle(); vt = null
                    if (dragging) {
                        // project the throw a little, then snap to the nearest corner
                        val cx = v.translationX + v.width / 2f + vx * 0.15f
                        val cy = v.translationY + v.height / 2f + vy * 0.15f
                        val left = cx < parent.width / 2f
                        val top = cy < (areaTop + parent.height - areaBottom) / 2f
                        corner = if (top) (if (left) TL else TR) else (if (left) BL else BR)
                        place(animate = true)
                    } else if (e.actionMasked == MotionEvent.ACTION_UP) {
                        if (controls.visibility == View.VISIBLE && controls.alpha > 0.5f) hideControls() else showControls()
                    }
                    true
                }
                else -> false
            }
        }
        container.setOnTouchListener(listener)
        // the overlay sits on top: drags/taps on its background behave the same; buttons still click
        controls.setOnTouchListener(listener)
    }

    companion object {
        const val TL = 0; const val TR = 1; const val BL = 2; const val BR = 3
    }
}
